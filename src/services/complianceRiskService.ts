/**
 * Standard legal disclaimer for automated AI compliance scanning
 */
export const COMPLIANCE_LEGAL_DISCLAIMER =
  'Advisory automated screening. This analysis is generated by AI pattern heuristics and microstock policy rules. It does not constitute formal legal counsel, trademark clearance, or copyright warranty.';

/**
 * Run deterministic + heuristic compliance and IP check on a StockFile
 */
export function evaluateComplianceRisks(file: StockFile): AssetRiskReport {
  const items: ComplianceRiskItem[] = [];
  const meta = file.metadata;
  const allText = `${meta.title} ${meta.description} ${meta.keywords.join(' ')}`;

  // 1. Scan for restricted trademarks & copyrighted brands in metadata
  for (const rule of RESTRICTED_TRADEMARK_PATTERNS) {
    const matches = allText.match(new RegExp(rule.pattern, 'gi'));
    if (matches && matches.length > 0) {
      const uniqueMatches = Array.from(new Set(matches.map((m) => m.toLowerCase())));
      items.push({
        id: `trademark_${rule.brand.replace(/\s+/g, '_').toLowerCase()}_${Date.now()}`,
        severity: rule.severity,
        category: rule.category,
        title: `Restricted Trademark / Brand: ${rule.brand}`,
        detail: `${rule.ruleExplanation} Detected terms: "${uniqueMatches.join('", "')}".`,
        detectedTerms: uniqueMatches,
        confidence: 0.98,
        isFactVsUncertainty: 'confirmed_rule',
        remediationAction: 'remove_terms',
      });
    }
  }

  // 2. Check for recognizable individuals without model release
  const hasPersonInKeywords = meta.keywords.some((k) =>
    /\b(person|man|woman|child|portrait|face|model|girl|boy|people|crowd)\b/i.test(k)
  );
  const peopleDetected = meta.containsPeople || hasPersonInKeywords;

  if (peopleDetected && !meta.editorial && !meta.releasesRequired) {
    items.push({
      id: `person_release_${Date.now()}`,
      severity: 'HIGH',
      category: 'recognizable_person',
      title: 'Recognizable Individual Detected — Model Release Needed',
      detail:
        'Identifiable people or portraits submitted for commercial licensing require a signed Model Release on Adobe, Shutterstock, and Getty. If not available, asset must be licensed as Editorial.',
      confidence: 0.9,
      isFactVsUncertainty: 'potential_risk',
      remediationAction: 'flag_release_required',
    });
  }

  // 3. Check for recognizable private property or modern architectural landmarks
  if (meta.containsRecognizableProperty && !meta.editorial && !meta.releasesRequired) {
    items.push({
      id: `property_release_${Date.now()}`,
      severity: 'HIGH',
      category: 'property_architecture',
      title: 'Recognizable Property or Protected Architecture',
      detail:
        'Private properties, ticketed venues, modern architectural landmarks, or distinct interior designs require a signed Property Release for commercial licensing.',
      confidence: 0.85,
      isFactVsUncertainty: 'potential_risk',
      remediationAction: 'flag_release_required',
    });
  }

  // 4. Commercial vs Editorial Suitability
  if (meta.isEditorialSuspected && !meta.editorial) {
    items.push({
      id: `editorial_recommendation_${Date.now()}`,
      severity: 'HIGH',
      category: 'editorial_suitability',
      title: 'Editorial Licensing Strongly Advised',
      detail:
        'This asset appears to depict public events, news, or recognizable third-party logos. Microstock platforms will reject this as commercial stock. Switch to Editorial with factual who/what/where/when caption.',
      confidence: 0.92,
      isFactVsUncertainty: 'human_review_required',
      remediationAction: 'mark_editorial',
    });
  }

  // 5. Watermarks / Signatures check
  if (/\b(watermark|copyright|all rights reserved|photo by|stock image|preview)\b/i.test(allText)) {
    items.push({
      id: `watermark_detected_${Date.now()}`,
      severity: 'CRITICAL',
      category: 'stock_watermark',
      title: 'Watermark or Artist Signature Tokens Detected',
      detail:
        'Keywords or captions containing "watermark", "photo by", or copyright notices lead to swift automated rejection by stock agency ingestion algorithms.',
      detectedTerms: ['watermark / attribution'],
      confidence: 0.99,
      isFactVsUncertainty: 'detected_fact',
      remediationAction: 'remove_terms',
    });
  }

  // 6. Keywords Count & Density Check
  if (meta.keywords.length < 5) {
    items.push({
      id: `keywords_too_few_${Date.now()}`,
      severity: 'HIGH',
      category: 'metadata_mismatch',
      title: 'Keyword Count Below Minimum Threshold',
      detail: 'Most agencies require at least 5 to 7 keywords. Assets with fewer tags suffer severe indexing penalties.',
      confidence: 1.0,
      isFactVsUncertainty: 'confirmed_rule',
      remediationAction: 'manual_review',
    });
  } else if (meta.keywords.length > 50) {
    items.push({
      id: `keywords_too_many_${Date.now()}`,
      severity: 'MEDIUM',
      category: 'metadata_mismatch',
      title: 'Keyword Count Exceeds Standard 50 Cap',
      detail: 'Adobe Stock, Shutterstock, and Freepik have hard 50-keyword limits. Excess keywords will be clipped.',
      confidence: 1.0,
      isFactVsUncertainty: 'confirmed_rule',
      remediationAction: 'remove_terms',
    });
  }

  // Calculate Overall Risk Level
  let overallRisk: 'pass' | 'caution' | 'high_risk' = 'pass';
  const hasCritical = items.some((i) => i.severity === 'CRITICAL');
  const hasHigh = items.some((i) => i.severity === 'HIGH');
  const hasMedium = items.some((i) => i.severity === 'MEDIUM');

  if (hasCritical) {
    overallRisk = 'high_risk';
  } else if (hasHigh || hasMedium) {
    overallRisk = 'caution';
  }

  const summary =
    overallRisk === 'high_risk'
      ? `CRITICAL RISK: ${items.length} issue(s) detected that will likely cause marketplace rejection or copyright claim.`
      : overallRisk === 'caution'
      ? `CAUTION: ${items.length} advisory issue(s) detected requiring review or remediation.`
      : 'COMPLIANT: No immediate copyright, trademark, or microstock policy violations detected.';

  return {
    overallRisk,
    summary,
    items,
    legalDisclaimer: COMPLIANCE_LEGAL_DISCLAIMER,
    timestamp: Date.now(),
  };
}
